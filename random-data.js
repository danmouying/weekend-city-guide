export const randomActivities = Object.entries(rows).flatMap(([party, items]) =>
  items.map(
    ([title, icon, category, budget, duration, description, search], i) => ({
      id: `${party}-${String(i + 1).padStart(2, "0")}`,
      party,
      title,
      icon,
      category,
      budget,
      duration,
      description,
      search,
    }),
  ),
);

export function poolFor(party) {
  return randomActivities.filter((activity) => activity.party === party);
}

// The caller can inject deterministic entropy in tests. Invalid inputs fail closed.
export function drawActivity(party, previousId = null, entropy = Math.random) {
  const pool = poolFor(party).filter((activity) => activity.id !== previousId);
  if (!pool.length) throw new RangeError("请选择有效的游玩人数");
  const value = entropy();
  if (!Number.isFinite(value) || value < 0 || value >= 1)
    throw new RangeError("随机数必须位于 [0,1)");
  return pool[Math.floor(value * pool.length)];
}
